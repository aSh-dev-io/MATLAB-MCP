%% =========================================================================
function [c0, vj] = solve_depletion(cref, vref, q)
%SOLVE_DEPLETION  Recover C0 and Vj from C(Vref) and the charge up to Vref.
%   Model:  C(V) = C0/(1 + V/Vj),  Q(Vref) = C0*Vj*ln(1 + Vref/Vj)
%   Using C(Vref) = C0/(1 + Vref/Vj) the charge reduces to
%       Q(Vref) = Cref * (Vj + Vref) * ln(1 + Vref/Vj)
%          = Cref * Vref * (1 + u) * ln(1 + u) / u,      u = Vref/Vj
%   The (1+u)ln(1+u)/u factor grows without bound as u grows, so a charge
%   larger than Cref*Vref (the Vj -> infinity asymptote) is perfectly
%   solvable. The factor falls monotonically as Vj rises, hence the bracket
%   runs from a small Vj (Q too large) to a large Vj (Q too small).

if q <= 0
    error('gan_parameters:solve_depletion', ...
        'Charge must be positive to extract a depletion shape.');
end

fn = @(vj) cref * (vj + vref) * log(1 + vref/max(vj, realmin)) - q;

lo = vref * 1e-6;
hi = vref * 1e6;
vj = fzero(fn, [lo, hi]);

c0 = cref * (1 + vref/vj);
end

%% =========================================================================
function vsc = solve_decay_scale(c0, vref, q)
%SOLVE_DECAY_SCALE  Find the voltage scale of C(V) = C0/(1 + V/Vsc) so that
%   the integral charge up to vref matches q.

if q >= c0*vref
    error('gan_parameters:solve_decay_scale', ...
        'Charge %.6g nC exceeds the rectangular bound C0*Vref = %.6g nC; no positive scale exists.', ...
        q*1e9, c0*vref*1e9);
end

fn = @(vsc) c0 * vsc * log(1 + vref/max(vsc, realmin)) - q;

lo = vref * 1e-6;
hi = vref * 1e6;
nudge = 0;
while fn(lo) > 0 && nudge < 80
    lo = lo / 10;
    nudge = nudge + 1;
end
vsc = fzero(fn, [lo, hi]);
end

%% =========================================================================
function vdsat = solve_vdsat(k, vov, va, id_target)
%SOLVE_VDSAT  Pick VDSAT so the saturation current at the given overdrive
%   equals the datasheet pulsed current rating. The function is not monotonic
%   over the whole positive axis, so the larger of the two roots is used.

fn = @(v) k * (vov*v - 0.5*v^2) * (1 + v/va) - id_target;

lo = vov * 1e-3;
hi = vov;
while fn(hi) < 0
    hi = hi * 2;
end
vdsat = fzero(fn, [lo, hi]);
end