    'cgd0', 'vjg', 'coss0', 'vjc', 'cgs0', 'vgsc', 'vth', 'vgs_min', ...
    'k', 'vsmooth', 'vdsat', 'va', 'idss', 'vdss_ref', 'igss', 'vgs_max', ...
    'vigs_iso', 'leak_ratio', 'leak_span', 'tnom', 'ron_ithresh', 'igss_leak_ratio'};

p.model.vector = [ ...
    p.caps.cgd0_F,   p.caps.vjg_V,   p.caps.coss0_F,  p.caps.vjc_V, ...
    p.caps.cgs_ref_F, p.caps.vgsc_V,  p.model.vth_V,   p.model.vgs_min_V, ...
    p.model.k_amp_per_v2, p.model.vsmooth_V, p.model.vdsat_V, p.model.va_V, ...
